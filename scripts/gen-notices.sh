#!/usr/bin/env bash
# Erzeugt THIRD_PARTY_NOTICES.md: Lizenzen aller Python-Pakete, die im Image der App landen.
# Läuft im selben Python-Basisimage wie das Dockerfile, damit die Paketliste übereinstimmt.
#   scripts/gen-notices.sh            (schreibt die Datei)
#   scripts/gen-notices.sh --check    (Exitcode 1, wenn die Datei veraltet ist)
# Indirekte Abhängigkeiten sind (noch) nicht gepinnt → vor jedem Release neu erzeugen, nicht in der CI prüfen.
set -euo pipefail
cd "$(dirname "$0")/.."
base=$(sed -n 's/^FROM //p' Dockerfile | head -1)
tmp=$(mktemp)
trap 'rm -f "$tmp"' EXIT

{
  cat <<'EOF'
# Third-party notices

QuietBoard itself is licensed under the MIT License (see `LICENSE`).

## Container images used unmodified (not distributed by this project)

| Component | License | Source |
| --- | --- | --- |
| Healthchecks | BSD-3-Clause | https://github.com/healthchecks/healthchecks |
| Beszel (hub and agent) | MIT | https://github.com/henrygd/beszel |
| signal-cli-rest-api (optional profile `signal`) | see upstream | https://github.com/bbernhard/signal-cli-rest-api |
| cloudflared (optional profile `tunnel`) | Apache-2.0 | https://github.com/cloudflare/cloudflared |

## Python packages included in the QuietBoard image

Generated by `scripts/gen-notices.sh` – do not edit by hand.
`certifi` is licensed under MPL-2.0 and included unmodified; its source is available at https://github.com/certifi/python-certifi
(see docs/decisions/0004-lizenz-certifi-mpl.md).

EOF
  echo '```text'
  docker run --rm -v "$PWD/requirements.lock:/r.txt:ro" "$base" sh -c \
    'pip install -q --root-user-action=ignore --disable-pip-version-check --require-hashes --no-deps -r /r.txt >/dev/null &&
     pip install -q --root-user-action=ignore --disable-pip-version-check pip-licenses==5.5.5 >/dev/null &&
     pip-licenses --from=mixed --with-urls --with-license-file --no-license-path --format=plain-vertical \
       --ignore-packages pip-licenses prettytable wcwidth pip setuptools wheel 2>/dev/null'
  echo '```'
} > "$tmp"

if [ "${1:-}" = "--check" ]; then
  if ! diff -q "$tmp" THIRD_PARTY_NOTICES.md >/dev/null 2>&1; then
    echo "THIRD_PARTY_NOTICES.md ist veraltet: scripts/gen-notices.sh" >&2
    exit 1
  fi
  echo "THIRD_PARTY_NOTICES.md aktuell"
else
  cp "$tmp" THIRD_PARTY_NOTICES.md
  echo "THIRD_PARTY_NOTICES.md geschrieben"
fi
